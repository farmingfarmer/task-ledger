#!/usr/bin/env python3
"""Make the synthetic ledger demo-ready: reconcile it, then decide it.

The synthetic profile is only useful on screen if it has a BOARD. Windows
generated by testdata/synth_meetings.py and extracted by a cadence tick
leave signals and proposals -- and nothing else, so the dashboard shows a
review queue over an empty board. This walks those proposals through the
same decision path a person would, for several people, leaving a state
with history: tasks in flight, some completed, some blocked, a handful of
rejections with reasons, and a live review queue that is not empty.

    export TL_SYNTH_DSN="host=localhost port=5432 dbname=taskintel_synth ..."
    python3 scripts/demo_seed_synthetic.py --dsn "$TL_SYNTH_DSN"

REFUSES to run against a database that looks like the real ledger, because
this writes decisions in other people's names -- defensible on invented
work, indefensible on theirs. Pass --i-know-what-this-is to override for a
differently-named synthetic database.

Nothing here is a new write path: accepts go through cli/review.py's
apply_accept(), which goes through apply_task_event(), which demands a
decision_id. The decisions this files are real decision records that
happen to have been made by a script on invented work -- and they are
labelled as such in their rationale.

Deterministic: the same database plus the same seed produces the same
board, so a demo can be rebuilt exactly. Python 3.8 compatible.
"""

import argparse
import datetime
import os
import sys

ROOT = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), ".."))
for sub in ("extraction", "reconciler", "cli", "policy"):
    sys.path.insert(0, os.path.join(ROOT, sub))

import psycopg2                     # noqa: E402
import psycopg2.extras              # noqa: E402

import board_io_pg                  # noqa: E402
import embedders                    # noqa: E402
import reconciler as rec_mod        # noqa: E402
import review as review_cli         # noqa: E402

# Rejections are what make the calibration panel say anything, and the
# reasons have to be ones the taxonomy actually offers.
REJECT_REASONS = ["wrong_owner", "not_a_task", "duplicate",
                  "wrong_status"]

# decisions has reject_note, not rationale -- the note rides along on
# both so every seeded decision is self-identifying in the ledger.
# Ops that move an existing task forward. A demo board with no
# completions shows a to-do list, not a ledger of what happened.
STATUS_OPS = ("complete_task", "update_status", "add_blocker",
              "resolve_blocker", "update_deadline", "reassign")

RATIONALE = "seeded demo decision on synthetic data"


def _ollama_chat(model, host):
    """Same call shape as run_reconcile's, so the judge behaves here
    exactly as it does in the real pipeline."""
    import json as _json
    import urllib.request as _u

    def call(messages):
        body = _json.dumps({"model": model, "messages": messages,
                            "stream": False,
                            "options": {"temperature": 0.0}}).encode("utf-8")
        req = _u.Request(host + "/api/chat", data=body,
                         headers={"Content-Type": "application/json"})
        with _u.urlopen(req, timeout=300) as resp:
            return _json.loads(resp.read().decode("utf-8"))["message"]["content"]
    return call


def refuse_if_real(dsn, override):
    """A database named like the live ledger is not a demo target."""
    name = ""
    for part in dsn.split():
        if part.startswith("dbname="):
            name = part.split("=", 1)[1]
    if override:
        return name
    if name in ("taskintel", "taskintel_prod"):
        raise SystemExit(
            "refusing to seed decisions into '{0}': this writes decision "
            "records in other people's names, which is fine on invented "
            "work and not on theirs. Point --dsn at a synthetic database "
            "(see PROFILES.md), or pass --i-know-what-this-is if this "
            "database really is synthetic.".format(name))
    return name


def users_with_signals(conn):
    with conn.cursor() as cur:
        cur.execute("SELECT DISTINCT user_ref FROM v_unconsumed_signals "
                    "ORDER BY user_ref")
        return [r[0] for r in cur.fetchall()]


def reconcile_for(dsn, user, run_id, judge=None):
    signals = board_io_pg.load_signals(dsn, user)
    if not signals:
        return None
    tasks, version = board_io_pg.load_board(dsn, user)
    # A judge matters here more than it looks: without one the reconciler
    # HOLDS closure signals rather than guessing, which is the correct
    # degraded behaviour and also means a seeded board has nothing
    # completed on it. "What got done" is half of what a demo is for.
    rec = rec_mod.Reconciler(embed=embedders.TokenEmbedder(),
                             judge_llm=judge)
    packet, rep = rec.reconcile(user, signals, tasks, version, run_id,
                                all_tasks=board_io_pg.load_all_boards(dsn))
    result = board_io_pg.write_packet(dsn, packet, rep["consumed"],
                                      rep["annotations"], run_id)
    return {"proposals": result["proposals"], "held": len(rep["held"])}


def decide_for(conn, user, keep_pending):
    """Accept most, reject a few with reasons, leave some undecided.

    The leftovers are the point as much as the accepts: a demo board with
    an empty review queue does not show the thing this system is about.
    """
    stats = {"accepted": 0, "rejected": 0, "left": 0, "invalid": 0}
    with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        packets = review_cli.pending_packets(cur, user)
        for packet in packets:
            props = review_cli.undecided_proposals(cur, packet["packet_id"])
            # Reserve from the TAIL, and never reserve an op that changes
            # an existing task. undecided_proposals sorts by confidence, so
            # reserving the first N held back the strongest proposals --
            # including both complete_task proposals in the set, which is
            # why a seeded board had nothing finished on it. A queue of
            # low-confidence creates is also the more honest queue: those
            # are the ones a person would actually still be deciding.
            cut = max(0, len(props) - keep_pending)
            for i, prop in enumerate(props):
                if i >= cut and prop["op"] not in STATUS_OPS:
                    stats["left"] += 1
                    continue
                ok, why = review_cli.still_valid(prop)
                if not ok:
                    stats["invalid"] += 1
                    continue
                reject = (i % 6 == 2)
                if reject:
                    cur.execute("""
                        INSERT INTO decisions (proposal_id, packet_id,
                          decision, reject_reason, reject_note, decided_by,
                          decided_at)
                        VALUES (%s,%s,'reject',%s,%s,%s,%s)
                        ON CONFLICT (proposal_id, decided_by) DO NOTHING""",
                        (prop["proposal_id"], packet["packet_id"],
                         REJECT_REASONS[i % len(REJECT_REASONS)],
                         RATIONALE, user, datetime.datetime.now()))
                    stats["rejected"] += 1
                    continue
                cur.execute("""
                    INSERT INTO decisions (proposal_id, packet_id, decision,
                      reject_note, decided_by, decided_at)
                    VALUES (%s,%s,'accept',%s,%s,%s)
                    ON CONFLICT (proposal_id, decided_by) DO NOTHING
                    RETURNING decision_id""",
                    (prop["proposal_id"], packet["packet_id"], RATIONALE,
                     user, datetime.datetime.now()))
                if cur.fetchone() is None:
                    continue                  # already decided; skip
                payload = dict(prop["payload"] or {})
                if review_cli.needs_owner(prop):
                    # The CLI refuses a bare accept here and prompts for an
                    # owner; a create nobody owns is the shape that put work
                    # on the wrong board. Standing in for that answer, not
                    # bypassing it.
                    payload["owner_ref"] = user
                review_cli.apply_accept(cur, user, prop, payload)
                stats["accepted"] += 1
            review_cli.record_state(
                cur, packet["packet_id"],
                "partially_decided" if stats["left"] else "closed")
    conn.commit()
    return stats


def seed_grants(conn, users):
    """Give the cross-person view something to show.

    Without grants every person sees only their own board, so the team
    panel, the sharing rail and the project view are all empty -- and
    those are the parts that argue for a shared ledger over a private
    to-do list. Levels are mixed on purpose: progress hides rationales,
    deciders, confidence, blocker wording and the whole provenance rail,
    so a demo that only ever shows full_trace never shows the redaction
    working.
    """
    made = 0
    with conn.cursor() as cur:
        for i, owner in enumerate(users):
            # Each person shares their board with the next two people in a
            # fixed rotation: one deep, one shallow.
            deep = users[(i + 1) % len(users)]
            shallow = users[(i + 2) % len(users)]
            for grantee, level in ((deep, "full_trace"),
                                   (shallow, "progress")):
                if grantee == owner:
                    continue
                cur.execute(
                    "SELECT grant_access(%s,%s,'user',%s,%s,%s,NULL)",
                    (owner, grantee, owner, level,
                     "seeded demo grant on synthetic data"))
                made += 1
    conn.commit()
    return made


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dsn", default=os.environ.get("TL_SYNTH_DSN")
                    or os.environ.get("DB_DSN"))
    ap.add_argument("--keep-pending", type=int, default=3,
                    help="proposals per person left undecided, so the "
                         "review queue on screen is not empty")
    ap.add_argument("--rounds", type=int, default=3,
                    help="reconcile/decide passes; later rounds match\n                         against the board the earlier ones built")
    ap.add_argument("--judge-model", default=None,
                    help="Ollama chat model for the judge band; without it "
                         "closure signals hold and nothing on the seeded "
                         "board is ever completed")
    ap.add_argument("--ollama-host", default="http://localhost:11434")
    ap.add_argument("--i-know-what-this-is", action="store_true",
                    dest="override")
    args = ap.parse_args()
    if not args.dsn:
        raise SystemExit("set TL_SYNTH_DSN or pass --dsn")

    name = refuse_if_real(args.dsn, args.override)
    judge = (_ollama_chat(args.judge_model, args.ollama_host)
             if args.judge_model else None)

    conn = psycopg2.connect(args.dsn)
    try:
        users = users_with_signals(conn)
    finally:
        conn.close()
    if not users:
        print("no pooled signals in {0} -- extract the synthetic inbox "
              "first (see PROFILES.md)".format(name))
        return 1

    print("seeding demo state in {0} for {1} people".format(name, len(users)))
    total = {"accepted": 0, "rejected": 0, "left": 0, "invalid": 0}

    # Rounds, because one pass cannot produce history. Reconciling consumes
    # what it can and HOLDS the rest awaiting corroboration; accepting turns
    # proposals into board state that the next round matches against, which
    # is what produces updates and closures on an existing task rather than
    # a flat list of creates. Only the last round leaves a queue.
    for r in range(1, args.rounds + 1):
        # Hold some back on EVERY round, not just the last. Reserving them
        # only at the end left an empty queue: by the final round the pool
        # was consumed and there was nothing left to leave, and a demo
        # whose "needs your review" panel is empty omits the one thing
        # this system is actually about.
        keep = args.keep_pending
        print("round {0}/{1}".format(r, args.rounds))
        for user in users:
            rep = reconcile_for(args.dsn, user,
                                "demo-seed-r{0}".format(r), judge)
            if rep and rep["proposals"]:
                print("  {0}: {1} proposal(s), {2} held".format(
                    user, rep["proposals"], rep["held"]))
        conn = psycopg2.connect(args.dsn)
        try:
            for user in users:
                s = decide_for(conn, user, keep)
                for k in total:
                    total[k] += s[k]
                if s["accepted"] or s["rejected"] or s["left"]:
                    print("  {0}: {1} accepted, {2} rejected, {3} left"
                          .format(user, s["accepted"], s["rejected"],
                                  s["left"]))
        finally:
            conn.close()

    conn = psycopg2.connect(args.dsn)
    try:
        grants = seed_grants(conn, users)
        with conn.cursor() as cur:
            cur.execute("SELECT count(*) FROM tasks_current "
                        "WHERE merged_into IS NULL")
            tasks = cur.fetchone()[0]
    finally:
        conn.close()
    print("shared {0} board grant(s) so the team view is not empty"
          .format(grants))

    print("\nboard now: {0} task(s), {1} accepted, {2} rejected with "
          "reasons, {3} still awaiting review".format(
              tasks, total["accepted"], total["rejected"], total["left"]))
    print("point the dashboard at it:")
    print('  export TL_SYNTH_DSN="{0}"'.format(args.dsn))
    print("  python3 integration/dashboard/dashboard_api.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
